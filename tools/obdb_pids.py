#!/usr/bin/env python3
"""
Regenerate docs/diagnostic-pids.md from the OBDb Toyota-Prius-Prime signalset.

Only keeps commands whose model-year filter covers the ZVW52 (2017-2022), and groups them by ECU.
Source: https://github.com/OBDb/Toyota-Prius-Prime (CC BY-SA 4.0) - the generated table inherits that licence.
"""
import json
import urllib.request
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SRC = "https://raw.githubusercontent.com/OBDb/Toyota-Prius-Prime/main/signalsets/v3/default.json"
YEARS = range(2017, 2023)

# best-effort guesses from usual Toyota diag addressing and the signals each header returns - not confirmed
ECU_NAMES = {
  "700": "? (odometer, 12V battery sensor)",
  "701": "?",
  "745": "? (displayed HV SOC)",
  "747": "Battery ECU (HV battery, 95 cells)",
  "750": "Body (main body ECU)",
  "780": "?",
  "7B0": "Skid control / brake (also returns SMR + charge contactor currents)",
  "7B1": "?",
  "7B3": "?",
  "7C0": "Combination meter",
  "7C4": "Air conditioning",
  "7D0": "?",
  "7D2": "Hybrid vehicle control ECU (power management)",
  "7E0": "Engine ECU",
  "7E1": "?",
}


def applies(cmd):
  f = cmd.get("filter")
  if not f:
    return True
  ok = set()
  if "from" in f:
    ok |= {y for y in YEARS if y >= f["from"]}
  if "to" in f:
    ok |= {y for y in YEARS if y <= f["to"]}
  ok |= set(f.get("years", [])) & set(YEARS)
  return bool(ok)


def fmt(fmt_):
  if not fmt_:
    return ""
  parts = [f"bits {fmt_.get('bix', 0)}+{fmt_.get('len', '')}"]
  if fmt_.get("sign"):
    parts.append("signed")
  if "mul" in fmt_:
    parts.append(f"x{fmt_['mul']}")
  if "div" in fmt_:
    parts.append(f"/{fmt_['div']}")
  if "add" in fmt_:
    parts.append(f"+{fmt_['add']}")
  if "unit" in fmt_:
    parts.append(fmt_["unit"])
  return " ".join(parts)


def main():
  with urllib.request.urlopen(SRC, timeout=60) as r:
    d = json.load(r)
  by_ecu = defaultdict(list)
  for c in d["commands"]:
    if not applies(c):
      continue
    req = " ".join(f"{k} {v}" for k, v in c["cmd"].items())
    for s in c["signals"]:
      by_ecu[(c["hdr"], c.get("rax", ""))].append((req, s["id"], s.get("name", ""), fmt(s.get("fmt"))))

  lines = [
    "# Diagnostic PIDs (ZVW52, 2017-22)",
    "",
    "Generated by `tools/obdb_pids.py` from [OBDb/Toyota-Prius-Prime](https://github.com/OBDb/Toyota-Prius-Prime) "
    "(CC BY-SA 4.0). Do not edit by hand - rerun the script.",
    "",
    "These are **polled** UDS/KWP requests (send to `hdr`, reply on `rax`), not broadcast traffic. "
    "Poll them while sniffing to get reference values for decoding broadcast frames.",
    "",
    "Note: the cell-voltage request `747 / 22 182E` is defined for 96 cells but a 2020 Prime returns 95.",
    "",
  ]
  for (hdr, rax), sigs in sorted(by_ecu.items()):
    lines += [f"## {hdr} -> {rax}: {ECU_NAMES.get(hdr, '?')} (guess)", "", "| Request | Signal | Description | Format |", "|---|---|---|---|"]
    for req, sid, name, f in sigs:
      lines.append(f"| `{req}` | `{sid}` | {name} | {f} |")
    lines.append("")
  out = REPO / "docs" / "diagnostic-pids.md"
  with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
  print(f"wrote {out.relative_to(REPO)}: {sum(len(v) for v in by_ecu.values())} signals on {len(by_ecu)} ECUs")


if __name__ == "__main__":
  main()
